/**
 * Fills `{name}` markers in a surface string.
 * @param {string} text
 * @param {Record<string, string | number>} [values]
 * @returns {string}
 */
export function fillCopy(text, values = {}) {
  return text.replace(/\{(\w+)\}/g, (whole, key) => (Object.hasOwn(values, key) ? String(values[key]) : whole));
}
