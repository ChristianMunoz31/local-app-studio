// Starts a phase: the worktree, npm ci, a port block and the facts section of the brief, written from the repo, the last gate
// JSON and the quarantine list. The owner's words and the product section stay the parent's.
//
//   node scripts/phase/new.js --slug <words-with-dashes> [--phase <N>] [--base <ref>] [--no-install] [--facts-out <file>]
//     [--workspace <dir>] [--dry-run]
//
// The phase number is the next one after the newest docs/phase<N> folder (--phase overrides). The worktree is
// ../las-wt-phase<N> beside the main checkout on branch feat/phase<N>-<slug> from --base (default main). The gate JSON read is the
// newest phase<N>-gates/gate.json of the workspace (or the live state file of this checkout). --dry-run prints the facts section
// and creates nothing: no worktree, no install, no port block, no file.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { OWNER_PIDS, OWNER_PORTS } from './lib/cleanupPlan.js';
import { gitExe, readWorktrees, runFile } from './lib/processTable.js';
import { writeFileAtomic } from './lib/gateRun.js';
import { resolveNpmCli } from '../lib/sandboxSafety.js';
import { REPO_ROOT, countLows, findGateFile, gitOut, lastEndedStep, notPassedSteps, parseFlags, readJsonFile, sectionLines, shortSha, statusPath, unwrapGate, wholeNumber, workspaceDir } from './common.js';
import { allocate, blockText, normalize } from './ports.js';

const USAGE = `Usage: node scripts/phase/new.js --slug <words-with-dashes> [--phase <N>] [--base <ref>] [--no-install] [--facts-out <file>]
         [--workspace <dir>] [--dry-run]`;
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+){0,7}$/;

/** The highest N of the docs/phase<N> folders, or 0. */
export function newestPhase(root) {
  try {
    return fs
      .readdirSync(path.join(root, 'docs'), { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => /^phase(\d+)$/.exec(e.name))
      .filter(Boolean)
      .reduce((m, x) => Math.max(m, Number(x[1])), 0);
  } catch {
    return 0;
  }
}

/** The budget rows of every build in a gate state, newest step result per id: `{ build, id, measured, limit, headroomPct }`. */
export function budgetFacts(state) {
  const seen = new Map();
  for (const s of state.steps) {
    for (const b of Array.isArray(s.result?.budgets) ? s.result.budgets : []) seen.set(`${s.build}:${b.id}`, { build: s.build, id: b.id, measured: b.measured, limit: b.limit, headroomPct: b.headroomPct });
  }
  return [...seen.values()];
}

/** Test totals out of the unit and e2e steps: `{ key, passed, skipped }`. */
export function testFacts(state) {
  return state.steps
    .filter((s) => s.result?.tests && Object.keys(s.result.tests).length > 0)
    .map((s) => {
      const t = Object.values(s.result.tests)[0];
      return { key: s.key, passed: t.passed ?? 0, skipped: t.skipped ?? 0, seconds: s.seconds ?? null };
    });
}

/**
 * The facts section. Pure: every input is already read.
 * @param {{ phase: number, branch: string, worktree: string, base: string, baseSha: string, baseSubject: string, day: string,
 *   gate: { state: object } | null, gateFile: string | null, flaky: string, ports: string | null, prevOpen: { questions: string[], lows: number, phase: number } | null,
 *   siblings: string[] }} i
 * @returns {string}
 */
export function factsSection(i) {
  const L = [`## 1. What exists today (facts)`, '', `Generated by scripts/phase/new.js on ${i.day} from the repo and the last gate JSON; nothing below was typed.`, ''];
  L.push(`- Base: ${i.base} at ${shortSha(i.baseSha)} (${i.baseSubject}). Work in \`${i.worktree}\` on branch \`${i.branch}\`.`);
  L.push(`- Port block for phase ${i.phase}: ${i.ports ?? 'none allocated (run scripts/phase/ports.js --allocate)'}. Owner ports never touched: ${OWNER_PORTS.join(', ')}. Owner node PIDs: ${OWNER_PIDS.join(', ')}.`);
  L.push('- Heavy steps (vitest, playwright, vite build, buildSidecar, cargo, loading a model), one at a time, foreground, through `node scripts/phase/wait.js --owner <name> -- <command>` (exit 75 = busy, call again). The phase gate takes the same lock.');
  L.push(i.siblings.length === 0 ? '- Other worktrees: none.' : `- Other worktrees: ${i.siblings.join(', ')}.`);
  if (i.gate === null) L.push('- Last gate: no gate JSON found.');
  else {
    const s = i.gate.state;
    const last = lastEndedStep(s);
    const wall = Math.round(s.steps.reduce((a, x) => a + (x.seconds ?? 0), 0));
    const slow = [...s.steps].filter((x) => x.seconds != null).sort((a, b) => b.seconds - a.seconds).slice(0, 5);
    L.push(`- Last gate: run ${s.runId} at ${shortSha(s.head)} (${path.basename(path.dirname(i.gateFile))}/${path.basename(i.gateFile)}), ${s.steps.length} steps, ${wall} s of steps${last ? `, last ${last.key} ${last.status}` : ''}.`);
    const bad = notPassedSteps(s).filter((x) => !/: pending$/.test(x));
    L.push(bad.length === 0 ? '- Last gate not passed: nothing.' : `- Last gate not passed: ${bad.join('; ')}.`);
    L.push(`- Slowest steps: ${slow.map((x) => `${x.key} ${x.seconds} s`).join(', ') || 'none recorded'}.`);
    const tests = testFacts(s);
    if (tests.length > 0) L.push(`- Test counts: ${tests.map((t) => `${t.key} ${t.passed} passed, ${t.skipped} skipped`).join('; ')}.`);
    const budgets = budgetFacts(s);
    if (budgets.length > 0) {
      L.push('- Budgets at that gate (measured of limit, headroom; the gate never raises one):');
      for (const b of budgets) L.push(`  - ${b.build} ${b.id}: ${b.measured} of ${b.limit} (${b.headroomPct} percent left)`);
    }
  }
  L.push('- Flaky and quarantined tests (`node scripts/ci/flakyReport.js list`):');
  for (const line of String(i.flaky).trim().split(/\r?\n/).filter(Boolean)) L.push(`  ${line}`);
  if (i.prevOpen !== null) {
    L.push(`- Carried from docs/phase${i.prevOpen.phase}/STATUS-phase${i.prevOpen.phase}.md: ${i.prevOpen.lows} tracked LOW${i.prevOpen.lows === 1 ? '' : 's'}, ${i.prevOpen.questions.length} owner question line${i.prevOpen.questions.length === 1 ? '' : 's'}.`);
    for (const q of i.prevOpen.questions) L.push(`  ${q.trim()}`);
  }
  return `${L.join('\n')}\n`;
}

/**
 * @param {string[]} argv
 * @param {object} [deps] out, err, root, homedir, now, run, readTrees, install
 * @returns {Promise<number>} 0 done or dry run, 1 a step failed, 2 usage
 */
export async function main(argv, deps = {}) {
  const d = {
    out: (l) => console.log(l),
    err: (l) => console.error(l),
    root: REPO_ROOT,
    homedir: undefined,
    now: () => new Date(),
    run: runFile,
    readTrees: readWorktrees,
    install: (cwd) => runFile(process.execPath, [resolveNpmCli(), 'ci'], { cwd, timeout: 900000 }),
    ...deps,
  };
  const parsed = parseFlags(argv, { slug: 'string', phase: 'string', base: 'string', 'no-install': 'bool', 'facts-out': 'string', workspace: 'string', 'dry-run': 'bool' });
  if ('error' in parsed) {
    d.err(`${parsed.error}\n${USAGE}`);
    return 2;
  }
  const o = parsed.opts;
  if (o.slug === null || !SLUG_RE.test(o.slug)) {
    d.err(`--slug needs lowercase words joined by dashes (at most 8)\n${USAGE}`);
    return 2;
  }
  const phase = o.phase === null ? newestPhase(d.root) + 1 : wholeNumber(o.phase);
  if (phase === null || phase < 1) {
    d.err(`--phase needs a number\n${USAGE}`);
    return 2;
  }
  const base = o.base ?? 'main';
  const workspace = o.workspace ?? workspaceDir(d.homedir);
  const listing = await d.readTrees(d.root).catch(() => ({ main: d.root, worktrees: [] }));
  const mainPath = listing.main || d.root;
  const worktree = path.join(path.dirname(mainPath), `las-wt-phase${phase}`);
  const branch = `feat/phase${phase}-${o.slug}`;
  const baseSha = await gitOut(['rev-parse', base], d.root, d.run);
  if (baseSha === null) {
    d.err(`unknown base ${base}`);
    return 2;
  }
  const baseSubject = (await gitOut(['log', '-1', '--format=%s', baseSha], d.root, d.run)) ?? '';

  const prev = newestPhaseWithGate(workspace, phase, d.root);
  const gateFile = findGateFile({ gate: null, root: d.root, phase: prev, workspace });
  const gate = gateFile === null ? null : unwrapGate(readJsonFile(gateFile));
  const flakyRun = await d.run(process.execPath, [path.join(d.root, 'scripts', 'ci', 'flakyReport.js'), 'list'], { cwd: d.root, timeout: 60000 });
  const flaky = `${flakyRun.stdout ?? ''}${flakyRun.stderr ?? ''}`.trim() || 'no list printed';
  const registryFile = path.join(workspace, 'phases.json');
  const registry = readJsonFile(registryFile);
  const have = blockText(registry, phase);
  const plan = have === null ? allocate(normalize(registry), phase, { now: d.now() }) : null;
  const ports = have ?? (plan?.entry ? `${plan.entry.ports[0]}-${plan.entry.ports[1]} (${o['dry-run'] ? 'would be allocated' : 'allocated now'})` : null);
  const prevStatus = prev === null || !fs.existsSync(statusPath(d.root, prev)) ? null : fs.readFileSync(statusPath(d.root, prev), 'utf8');
  const prevOpen = prevStatus === null ? null : { phase: prev, questions: sectionLines(prevStatus, 'Owner questions').filter((l) => l.trim() !== ''), lows: countLows(sectionLines(prevStatus, 'Tracked LOWs')) };
  const facts = factsSection({
    phase,
    branch,
    worktree,
    base,
    baseSha,
    baseSubject,
    day: d.now().toISOString().slice(0, 10),
    gate,
    gateFile,
    flaky,
    ports,
    prevOpen,
    siblings: listing.worktrees.map((w) => path.basename(w.path)),
  });
  if (o['dry-run']) {
    d.out(facts.trimEnd());
    d.out(`dry run: nothing created (worktree ${worktree}, branch ${branch})`);
    return 0;
  }

  if (fs.existsSync(worktree)) {
    d.err(`refused: ${worktree} already exists`);
    return 1;
  }
  const git = gitExe();
  if (git === null) {
    d.err('git not found on an absolute PATH entry');
    return 1;
  }
  const add = await d.run(git, ['worktree', 'add', worktree, '-b', branch, base], { cwd: d.root, timeout: 120000 });
  if (add.code !== 0) {
    d.err(`git worktree add failed: ${String(add.stderr).trim().split(/\r?\n/)[0]}`);
    return 1;
  }
  d.out(`created worktree ${worktree} on ${branch}`);
  if (!o['no-install']) {
    const ci = await d.install(worktree);
    if (ci.code !== 0) {
      d.err(`npm ci failed (exit ${ci.code ?? 'none'}): ${String(ci.stderr).trim().split(/\r?\n/).pop()}`);
      return 1;
    }
    d.out('npm ci done');
  }
  if (plan !== null && plan.created) {
    fs.mkdirSync(workspace, { recursive: true });
    writeFileAtomic(registryFile, `${JSON.stringify(plan.registry, null, 2)}\n`);
    d.out(`port block ${plan.entry.ports[0]}-${plan.entry.ports[1]} written to ${registryFile}`);
  }
  const outFile = path.resolve(o['facts-out'] ?? path.join(workspace, `BRIEF-phase${phase}-facts.md`));
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, facts);
  d.out(`wrote ${outFile}`);
  return 0;
}

/** The newest phase below `phase` that has a gate JSON in the workspace, else the newest phase with a docs folder, else null. */
function newestPhaseWithGate(workspace, phase, root) {
  for (let n = phase - 1; n >= 1 && n > phase - 40; n -= 1) {
    if (fs.existsSync(path.join(workspace, `phase${n}-gates`, 'gate.json'))) return n;
  }
  const docs = newestPhase(root);
  return docs > 0 && docs < phase ? docs : null;
}

